create table public.debt_adjustments (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  debt_type text not null check (debt_type in ('loan', 'credit_card')),
  loan_id bigint references public.loans(id) on delete cascade,
  credit_card_id bigint references public.credit_cards(id) on delete cascade,
  adjustment_type text not null check (
    adjustment_type in (
      'finance_charge',
      'late_fee',
      'over_limit_fee',
      'annual_fee',
      'additional_interest',
      'collection_fee',
      'restructuring_fee',
      'other_charge',
      'credit',
      'reversal'
    )
  ),
  amount numeric(14,2) not null check (amount > 0),
  signed_amount numeric(14,2) generated always as (
    case when adjustment_type in ('credit', 'reversal') then -amount else amount end
  ) stored,
  effective_date date not null default current_date,
  due_date date not null,
  description text not null default '',
  source_transaction_id bigint references public.transactions(id) on delete set null,
  reverses_adjustment_id bigint references public.debt_adjustments(id) on delete restrict,
  status text not null default 'posted' check (status in ('posted', 'void')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint debt_adjustments_target_check check (
    (debt_type = 'loan' and loan_id is not null and credit_card_id is null)
    or
    (debt_type = 'credit_card' and credit_card_id is not null and loan_id is null)
  ),
  constraint debt_adjustments_reversal_check check (
    (adjustment_type = 'reversal' and reverses_adjustment_id is not null)
    or
    (adjustment_type <> 'reversal' and reverses_adjustment_id is null)
  )
);

create table public.debt_payments (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  debt_type text not null check (debt_type in ('loan', 'credit_card')),
  loan_id bigint references public.loans(id) on delete cascade,
  credit_card_id bigint references public.credit_cards(id) on delete cascade,
  amount numeric(14,2) not null check (amount > 0),
  payment_date date not null default current_date,
  source_account_key text,
  source_transaction_id bigint references public.transactions(id) on delete set null,
  legacy_due_key text,
  status text not null default 'posted' check (status in ('posted', 'void')),
  note text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint debt_payments_target_check check (
    (debt_type = 'loan' and loan_id is not null and credit_card_id is null)
    or
    (debt_type = 'credit_card' and credit_card_id is not null and loan_id is null)
  )
);

create table public.payment_allocations (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  payment_id bigint not null references public.debt_payments(id) on delete cascade,
  adjustment_id bigint references public.debt_adjustments(id) on delete restrict,
  component text not null check (
    component in (
      'principal',
      'interest',
      'finance_charge',
      'late_fee',
      'penalty',
      'fee',
      'other'
    )
  ),
  amount numeric(14,2) not null check (amount > 0),
  created_at timestamptz not null default now()
);

create or replace function public.validate_debt_accounting_row()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  owner_id uuid;
  reversed_row public.debt_adjustments%rowtype;
begin
  if new.source_transaction_id is not null then
    perform pg_advisory_xact_lock(
      hashtextextended('ppb-source-transaction:' || new.source_transaction_id::text, 0)
    );
  end if;

  if new.debt_type = 'loan' then
    select user_id into owner_id from public.loans where id = new.loan_id;
  else
    select user_id into owner_id from public.credit_cards where id = new.credit_card_id;
  end if;

  if owner_id is null or owner_id <> new.user_id then
    raise exception 'Debt target does not belong to the user';
  end if;

  if new.source_transaction_id is not null then
    select user_id into owner_id
    from public.transactions
    where id = new.source_transaction_id;

    if owner_id is null or owner_id <> new.user_id then
      raise exception 'Source transaction does not belong to the user';
    end if;

    if tg_table_name = 'debt_adjustments'
       and exists (
         select 1 from public.debt_payments
         where user_id = new.user_id
           and source_transaction_id = new.source_transaction_id
           and status = 'posted'
       ) then
      raise exception 'Source transaction is already linked to a payment';
    end if;

    if tg_table_name = 'debt_payments'
       and exists (
         select 1 from public.debt_adjustments
         where user_id = new.user_id
           and source_transaction_id = new.source_transaction_id
           and status = 'posted'
       ) then
      raise exception 'Source transaction is already linked to an adjustment';
    end if;
  end if;

  if tg_table_name = 'debt_adjustments' and new.reverses_adjustment_id is not null then
    perform pg_advisory_xact_lock(
      hashtextextended('ppb-adjustment-reversal:' || new.reverses_adjustment_id::text, 0)
    );

    select * into reversed_row
    from public.debt_adjustments
    where id = new.reverses_adjustment_id;

    if reversed_row.id is null
       or reversed_row.user_id <> new.user_id
       or reversed_row.debt_type <> new.debt_type
       or reversed_row.loan_id is distinct from new.loan_id
       or reversed_row.credit_card_id is distinct from new.credit_card_id
       or reversed_row.adjustment_type = 'reversal'
       or reversed_row.status <> 'posted'
       or reversed_row.amount <> new.amount then
      raise exception 'Invalid adjustment reversal';
    end if;

    if exists (
      select 1
      from public.debt_adjustments
      where reverses_adjustment_id = new.reverses_adjustment_id
        and status = 'posted'
        and id is distinct from new.id
    ) then
      raise exception 'Adjustment has already been reversed';
    end if;
  end if;

  return new;
end;
$$;

create or replace function public.validate_payment_allocation()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  payment_row public.debt_payments%rowtype;
  adjustment_row public.debt_adjustments%rowtype;
  allocated_total numeric(14,2);
begin
  perform pg_advisory_xact_lock(
    hashtextextended('ppb-payment-allocation:' || new.payment_id::text, 0)
  );

  select * into payment_row
  from public.debt_payments
  where id = new.payment_id;

  if payment_row.id is null
     or payment_row.user_id <> new.user_id
     or payment_row.status <> 'posted' then
    raise exception 'Payment does not belong to the user';
  end if;

  if new.adjustment_id is not null then
    perform pg_advisory_xact_lock(
      hashtextextended('ppb-adjustment-allocation:' || new.adjustment_id::text, 0)
    );

    select * into adjustment_row
    from public.debt_adjustments
    where id = new.adjustment_id;

    if adjustment_row.id is null
       or adjustment_row.user_id <> new.user_id
       or adjustment_row.debt_type <> payment_row.debt_type
       or adjustment_row.loan_id is distinct from payment_row.loan_id
       or adjustment_row.credit_card_id is distinct from payment_row.credit_card_id
       or adjustment_row.status <> 'posted'
       or adjustment_row.adjustment_type in ('credit', 'reversal') then
      raise exception 'Adjustment does not belong to the payment debt';
    end if;

    if new.component = 'principal'
       or (adjustment_row.adjustment_type = 'finance_charge' and new.component <> 'finance_charge')
       or (adjustment_row.adjustment_type = 'additional_interest' and new.component <> 'interest')
       or (adjustment_row.adjustment_type = 'late_fee' and new.component <> 'penalty')
       or (adjustment_row.adjustment_type in (
             'over_limit_fee', 'annual_fee', 'collection_fee',
             'restructuring_fee', 'other_charge'
           ) and new.component not in ('fee', 'other')) then
      raise exception 'Allocation component does not match the adjustment type';
    end if;

    select coalesce(sum(amount), 0)
      into allocated_total
    from public.payment_allocations
    where adjustment_id = new.adjustment_id
      and id is distinct from new.id;

    if allocated_total + new.amount > adjustment_row.amount then
      raise exception 'Allocations cannot exceed the adjustment amount';
    end if;
  elsif new.component not in ('principal', 'interest', 'other') then
    raise exception 'Charge, penalty, and fee allocations require an adjustment';
  end if;

  select coalesce(sum(amount), 0)
    into allocated_total
  from public.payment_allocations
  where payment_id = new.payment_id
    and id is distinct from new.id;

  if allocated_total + new.amount > payment_row.amount then
    raise exception 'Allocations cannot exceed the payment amount';
  end if;

  return new;
end;
$$;

