create or replace function public.record_debt_adjustment(
  p_user_id uuid,
  p_debt_type text,
  p_debt_id bigint,
  p_adjustment_type text,
  p_amount numeric,
  p_effective_date date,
  p_due_date date,
  p_description text,
  p_transaction_id bigint,
  p_transaction_category text,
  p_transaction_note text,
  p_reverses_adjustment_id bigint default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_previous_balance numeric(14,2);
  v_current_balance numeric(14,2);
  balance_delta numeric(14,2);
  adjustment_id bigint;
begin
  if (select auth.uid()) is distinct from p_user_id
     and coalesce((select auth.role()), '') <> 'service_role' then
    raise exception 'Not authorized';
  end if;
  if p_amount is null or p_amount <= 0 then raise exception 'Adjustment amount must be positive'; end if;
  if (p_adjustment_type = 'reversal') <> (p_reverses_adjustment_id is not null) then
    raise exception 'A reversal must identify exactly one adjustment';
  end if;
  balance_delta := case when p_adjustment_type in ('credit', 'reversal') then -p_amount else p_amount end;

  if p_debt_type = 'loan' then
    select l.balance into v_previous_balance from public.loans l
      where id = p_debt_id and user_id = p_user_id for update;
    if v_previous_balance is null then raise exception 'Loan not found'; end if;
    v_current_balance := round(v_previous_balance + balance_delta, 2);
    if v_current_balance < 0 then raise exception 'Adjustment exceeds the debt balance'; end if;
    update public.loans set balance = v_current_balance where id = p_debt_id;
  elsif p_debt_type = 'credit_card' then
    select c.current_balance into v_previous_balance from public.credit_cards c
      where id = p_debt_id and user_id = p_user_id for update;
    if v_previous_balance is null then raise exception 'Credit card not found'; end if;
    v_current_balance := round(v_previous_balance + balance_delta, 2);
    if v_current_balance < 0 then raise exception 'Adjustment exceeds the debt balance'; end if;
    update public.credit_cards
      set current_balance = v_current_balance,
          statement_balance = greatest(0, round(statement_balance + balance_delta, 2))
      where id = p_debt_id;
  else
    raise exception 'Invalid debt type';
  end if;

  insert into public.transactions(id, user_id, kind, amount, category, note, date)
  values (
    p_transaction_id, p_user_id,
    case when balance_delta < 0 then 'income' else 'expense' end,
    p_amount, p_transaction_category, p_transaction_note, p_effective_date
  );

  insert into public.debt_adjustments(
    user_id, debt_type, loan_id, credit_card_id, adjustment_type, amount,
    effective_date, due_date, description, source_transaction_id, reverses_adjustment_id
  ) values (
    p_user_id, p_debt_type,
    case when p_debt_type = 'loan' then p_debt_id end,
    case when p_debt_type = 'credit_card' then p_debt_id end,
    p_adjustment_type, p_amount, p_effective_date, p_due_date,
    coalesce(p_description, ''), p_transaction_id, p_reverses_adjustment_id
  ) returning id into adjustment_id;

  return jsonb_build_object(
    'transaction_id', p_transaction_id, 'adjustment_id', adjustment_id,
    'previous_balance', v_previous_balance, 'current_balance', v_current_balance
  );
end;
$$;

create or replace function public.record_debt_payment(
  p_user_id uuid,
  p_debt_type text,
  p_debt_id bigint,
  p_amount numeric,
  p_payment_date date,
  p_due_date date,
  p_source_account_key text,
  p_transaction_id bigint,
  p_transaction_category text,
  p_transaction_note text,
  p_advanced_due_date date default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_previous_balance numeric(14,2);
  v_current_balance numeric(14,2);
  payment_id bigint;
  principal_amount numeric(14,2);
  remaining_amount numeric(14,2);
  outstanding_charges numeric(14,2);
  available_adjustment numeric(14,2);
  allocation_amount numeric(14,2);
  component_name text;
  adjustment_row record;
begin
  if (select auth.uid()) is distinct from p_user_id
     and coalesce((select auth.role()), '') <> 'service_role' then
    raise exception 'Not authorized';
  end if;
  if p_amount is null or p_amount <= 0 then raise exception 'Payment amount must be positive'; end if;

  if p_debt_type = 'loan' then
    select l.balance into v_previous_balance from public.loans l
      where id = p_debt_id and user_id = p_user_id for update;
  elsif p_debt_type = 'credit_card' then
    select c.current_balance into v_previous_balance from public.credit_cards c
      where id = p_debt_id and user_id = p_user_id for update;
  else
    raise exception 'Invalid debt type';
  end if;
  if v_previous_balance is null then raise exception 'Debt not found'; end if;
  if p_amount > v_previous_balance then raise exception 'Payment exceeds the debt balance'; end if;

  select greatest(0, coalesce(sum(
    case when a.signed_amount > 0
      then greatest(0, a.signed_amount - coalesce(x.allocated, 0))
      else a.signed_amount end
  ), 0)) into outstanding_charges
  from public.debt_adjustments a
  left join lateral (
    select sum(pa.amount) allocated from public.payment_allocations pa where pa.adjustment_id = a.id
  ) x on true
  where a.user_id = p_user_id and a.debt_type = p_debt_type and a.status = 'posted'
    and ((p_debt_type = 'loan' and a.loan_id = p_debt_id)
      or (p_debt_type = 'credit_card' and a.credit_card_id = p_debt_id));

  principal_amount := least(p_amount, greatest(0, v_previous_balance - outstanding_charges));
  remaining_amount := round(p_amount - principal_amount, 2);
  v_current_balance := round(v_previous_balance - p_amount, 2);

  insert into public.transactions(id, user_id, kind, amount, category, note, date)
  values (p_transaction_id, p_user_id, 'expense', p_amount, p_transaction_category, p_transaction_note, p_payment_date);

  insert into public.debt_payments(
    user_id, debt_type, loan_id, credit_card_id, amount, payment_date,
    source_account_key, source_transaction_id, legacy_due_key
  ) values (
    p_user_id, p_debt_type,
    case when p_debt_type = 'loan' then p_debt_id end,
    case when p_debt_type = 'credit_card' then p_debt_id end,
    p_amount, p_payment_date, p_source_account_key, p_transaction_id,
    p_debt_type || ':' || p_debt_id || ':' || p_due_date
  ) returning id into payment_id;

  if principal_amount > 0 then
    insert into public.payment_allocations(user_id, payment_id, component, amount)
    values (p_user_id, payment_id, 'principal', principal_amount);
  end if;

  for adjustment_row in
    select a.*, coalesce(x.allocated, 0) allocated
    from public.debt_adjustments a
    left join lateral (
      select sum(pa.amount) allocated from public.payment_allocations pa where pa.adjustment_id = a.id
    ) x on true
    where remaining_amount > 0 and a.user_id = p_user_id
      and a.debt_type = p_debt_type and a.status = 'posted'
      and a.adjustment_type not in ('credit', 'reversal')
      and ((p_debt_type = 'loan' and a.loan_id = p_debt_id)
        or (p_debt_type = 'credit_card' and a.credit_card_id = p_debt_id))
    order by a.due_date, a.effective_date, a.id
    for update of a
  loop
    available_adjustment := greatest(0, adjustment_row.amount - adjustment_row.allocated);
    allocation_amount := least(remaining_amount, available_adjustment);
    if allocation_amount <= 0 then continue; end if;
    component_name := case adjustment_row.adjustment_type
      when 'finance_charge' then 'finance_charge'
      when 'additional_interest' then 'interest'
      when 'late_fee' then 'penalty'
      when 'other_charge' then 'other'
      else 'fee' end;
    insert into public.payment_allocations(user_id, payment_id, adjustment_id, component, amount)
    values (p_user_id, payment_id, adjustment_row.id, component_name, allocation_amount);
    remaining_amount := round(remaining_amount - allocation_amount, 2);
  end loop;

  if remaining_amount <> 0 then raise exception 'Payment allocation could not be reconciled'; end if;

  if p_debt_type = 'loan' then
    update public.loans set balance = v_current_balance,
      due = coalesce(p_advanced_due_date, due) where id = p_debt_id;
  else
    update public.credit_cards set current_balance = v_current_balance,
      statement_balance = greatest(0, round(statement_balance - p_amount, 2))
      where id = p_debt_id;
  end if;

  return jsonb_build_object(
    'transaction_id', p_transaction_id, 'payment_id', payment_id,
    'previous_balance', v_previous_balance, 'current_balance', v_current_balance
  );
end;
$$;

